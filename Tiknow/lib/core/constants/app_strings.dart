  static String translate(
    String languageCode,
    String key, {
    Map<String, String>? args,
  }) {
    final table = languageCode == 'en' ? en : tr;
    var text = table[key] ?? tr[key] ?? key;
    if (args != null) {
      args.forEach((name, value) => text = text.replaceAll('{$name}', value));
    }
    return text;
  }

